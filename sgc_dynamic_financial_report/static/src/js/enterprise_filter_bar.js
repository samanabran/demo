/** @odoo-module **/

import { Component, useState, onWillStart, onMounted } from "@odoo/owl";
import { useService } from "@web/core/utils/hooks";
import { rpc } from "@web/core/network/rpc";
import { Dropdown } from "@web/core/dropdown/dropdown";

/**
 * Single filter widget. Rendering is entirely driven by ``filterDef.widget``
 * (from FILTER_DEFINITIONS in models/sgc_report_metadata.py) — no report
 * ever hardcodes which widget a filter key uses.
 */
export class DfrFilterWidget extends Component {
    static template = "sgc_dynamic_financial_report.DfrFilterWidget";
    static props = {
        filterDef: Object,
        value: { optional: true },
        onChange: Function,
    };

    setup() {
        this.orm = useService("orm");
        this.state = useState({
            searchTerm: "",
            searchResults: [],
            searchOpen: false,
        });
        this._searchDebounce = null;
    }

    get widget() {
        return this.props.filterDef.widget;
    }

    // ── many2one / many2many_tags: debounced ORM name_search ────────────
    onSearchInput(ev) {
        const term = ev.target.value;
        this.state.searchTerm = term;
        clearTimeout(this._searchDebounce);
        this._searchDebounce = setTimeout(() => this._runSearch(term), 300);
    }

    async _runSearch(term) {
        const filterDef = this.props.filterDef;
        if (!filterDef.model) {
            return;
        }
        const domain = filterDef.domain ? JSON.parse(filterDef.domain.replace(/'/g, '"')) : [];
        const results = await this.orm.call(filterDef.model, "name_search", [], {
            name: term,
            args: domain,
            operator: "ilike",
            limit: 20,
        });
        this.state.searchResults = results.map(([id, display_name]) => ({ id, display_name }));
        this.state.searchOpen = true;
    }

    selectMany2One(option) {
        this.props.onChange(option.id);
        this.state.searchTerm = option.display_name;
        this.state.searchOpen = false;
    }

    selectMany2ManyTag(option) {
        const current = Array.isArray(this.props.value) ? this.props.value : [];
        if (!current.includes(option.id)) {
            this.props.onChange([...current, option.id]);
        }
        this.state.searchTerm = "";
        this.state.searchOpen = false;
    }

    removeMany2ManyTag(id) {
        const current = Array.isArray(this.props.value) ? this.props.value : [];
        this.props.onChange(current.filter((existing) => existing !== id));
    }

    // ── date_range ───────────────────────────────────────────────────
    onDateFromChange(ev) {
        this.props.onChange([ev.target.value, this.props.value ? this.props.value[1] : ""]);
    }

    onDateToChange(ev) {
        this.props.onChange([this.props.value ? this.props.value[0] : "", ev.target.value]);
    }

    // ── boolean ──────────────────────────────────────────────────────
    onBooleanToggle(ev) {
        this.props.onChange(ev.target.checked);
    }

    // ── selection ────────────────────────────────────────────────────
    onSelectionChange(ev) {
        this.props.onChange(ev.target.value);
    }
}

/**
 * Enterprise filter bar: a single horizontal Bootstrap 5 toolbar row on
 * desktop, generated entirely from the report's metadata declaration
 * (``/sgc/dfr/metadata``). Never hardcodes a per-report filter layout —
 * it only ever walks ``toolbar_filters`` and ``more_filters`` from the
 * metadata the server returns for the active ``report_type``.
 */
export class EnterpriseFilterBar extends Component {
    static template = "sgc_dynamic_financial_report.EnterpriseFilterBar";
    static components = { DfrFilterWidget, Dropdown };
    static props = {
        reportType: String,
        onGenerate: Function,
        onExport: { type: Function, optional: true },
        onExportPdf: { type: Function, optional: true },
    };

    setup() {
        this.state = useState({
            registry: null,
            metadata: null,
            values: {},
            moreFiltersOpen: false,
            loading: true,
        });
        onWillStart(async () => {
            await this._loadRegistry();
            this._loadReportMetadata(this.props.reportType);
            this.state.loading = false;
        });

        // Render the report straight away using the server's smart defaults
        // rather than waiting for an explicit click. The parent's onWillStart
        // (which creates the wizard record) has already resolved by the time a
        // child mounts, so wizardId is guaranteed to exist here. Guarded so it
        // can only ever fire once per mount.
        this._autoGenerated = false;
        onMounted(() => {
            if (!this._autoGenerated && this.canGenerate) {
                this._autoGenerated = true;
                this.props.onGenerate({ ...this.state.values });
            }
        });
    }

    async _loadRegistry() {
        this.state.registry = await rpc("/sgc/dfr/metadata", {});
    }

    _loadReportMetadata(reportType) {
        const meta = this.state.registry && this.state.registry.reports
            ? this.state.registry.reports[reportType]
            : null;
        this.state.metadata = meta || null;
        // Server-side _with_smart_defaults() already injected Company (current
        // user) and Date (FY start -> today) into meta.defaults. Trust the
        // server as the single source of truth for what counts as a default.
        this.state.values = { ...((meta && meta.defaults) || {}) };
    }

    get toolbarFilterDefs() {
        if (!this.state.metadata) {
            return [];
        }
        return this.state.metadata.toolbar_filters.map((key) => ({
            key,
            ...this.state.registry.filters[key],
        }));
    }

    get moreFilterDefs() {
        if (!this.state.metadata) {
            return [];
        }
        return this.state.metadata.more_filters.map((key) => ({
            key,
            ...this.state.registry.filters[key],
        }));
    }

    isRequired(key) {
        return !!(this.state.metadata && this.state.metadata.required_filters.includes(key));
    }

    get canGenerate() {
        if (!this.state.metadata) {
            return false;
        }
        return this.state.metadata.required_filters.every(
            (key) => this.state.values[key] !== undefined && this.state.values[key] !== ""
        );
    }

    toggleMoreFilters() {
        this.state.moreFiltersOpen = !this.state.moreFiltersOpen;
    }

    onFilterValueChange(key, value) {
        this.state.values[key] = value;
    }

    /** Whether a filter currently holds a meaningful (non-empty) value. */
    _hasValue(key) {
        const value = this.state.values[key];
        if (value === undefined || value === null || value === "" || value === false) {
            return false;
        }
        if (Array.isArray(value)) {
            return value.some((entry) => entry !== undefined && entry !== null && entry !== "");
        }
        return true;
    }

    /**
     * Short label shown on a collapsed filter pill, so the toolbar still
     * communicates the active value without the dropdown being expanded.
     */
    summaryFor(filterDef) {
        const value = this.state.values[filterDef.key];
        if (!this._hasValue(filterDef.key)) {
            switch (filterDef.widget) {
                case "many2many_tags":
                    return "All";
                case "boolean":
                case "boolean_with_many2many":
                case "boolean_with_date_range":
                    return "Off";
                default:
                    return "Any";
            }
        }
        switch (filterDef.widget) {
            case "date_range": {
                const [from, to] = value;
                return `${from || "…"} → ${to || "…"}`;
            }
            case "many2many_tags":
                return `${value.length} selected`;
            case "boolean":
            case "boolean_with_many2many":
            case "boolean_with_date_range":
                return "On";
            case "selection": {
                const option = (filterDef.options || []).find((opt) => opt[0] === value);
                return option ? option[1] : String(value);
            }
            case "many2one":
                return "Selected";
            case "readonly_company_setting":
                return "Company setting";
            default:
                return String(value);
        }
    }

    get moreFilterActiveCount() {
        return this.moreFilterDefs.filter((def) => this._hasValue(def.key)).length;
    }

    /** Active filters rendered as chips under the toolbar. */
    get activeChips() {
        return [...this.toolbarFilterDefs, ...this.moreFilterDefs]
            .filter((def) => this._hasValue(def.key))
            .map((def) => ({
                key: def.key,
                label: def.label,
                value: this.summaryFor(def),
            }));
    }

    onGenerateClick() {
        // "After Apply, automatically collapse panel." — mission spec.
        this.state.moreFiltersOpen = false;
        this.props.onGenerate({ ...this.state.values });
    }

    onExportClick() {
        if (this.props.onExport) {
            this.props.onExport({ ...this.state.values });
        }
    }

    onExportPdfClick() {
        if (this.props.onExportPdf) {
            this.props.onExportPdf({ ...this.state.values });
        }
    }

    onResetClick() {
        this.state.values = { ...((this.state.metadata && this.state.metadata.defaults) || {}) };
    }
}
